use crate::endpoints::orders::schema::address::{Address, PersonFullName, PhoneWithType};
use crate::endpoints::orders::schema::source::token::PaymentUsage;
use crate::endpoints::orders::schema::source::{PaymentInitiator, PaymentType, VaultStoreInValue};
use serde::{Deserialize, Serialize};
use typed_builder::TypedBuilder;

#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, TypedBuilder)]
pub struct CardSource {
    /// The card holder's name as it appears on the card.
    #[builder(default, setter(strip_option, into))]
    pub name: Option<String>,

    /// The primary account number (PAN) for the payment card.
    #[builder(default, setter(strip_option, into))]
    pub number: Option<String>,

    /// The three- or four-digit security code of the card.
    /// Also known as the CVV, CVC, CVN, CVE, or CID.
    /// This parameter cannot be present in the request when payment_initiator=MERCHANT.
    #[builder(default, setter(strip_option, into))]
    pub security_code: Option<String>,

    /// The card expiration year and month,
    /// in Internet date format For example: 2028-04
    #[builder(default, setter(strip_option, into))]
    pub expiry: Option<String>,

    /// The billing address for this card.
    /// Supports only the address_line_1, address_line_2, admin_area_1, admin_area_2, postal_code, and country_code properties.
    #[builder(default, setter(strip_option, into))]
    pub billing_address: Option<Address>,

    // Additional attributes associated with the use of this card.
    #[builder(default, setter(strip_option, into))]
    pub attributes: Option<CardAttributes>,

    /// Provides additional details to process a payment using a card that has been stored or is intended to be stored (also referred to as stored_credential or card-on-file).
    #[builder(default, setter(strip_option, into))]
    pub stored_credential: Option<CardStoredCredential>,

    /// The PayPal-generated ID for the saved card payment source.
    /// Typically stored on the merchant's server.
    #[builder(default, setter(strip_option, into))]
    pub vault_id: Option<String>,

    /// The PayPal-generated, short-lived, one-time-use token,
    /// used to communicate payment information to PayPal for transaction processing.
    #[builder(default, setter(strip_option, into))]
    pub single_use_token: Option<String>,

    /// A 3rd party network token refers to a network token that the merchant provisions from and vaults with an external TSP (Token Service Provider) other than PayPal.
    #[builder(default, setter(strip_option, into))]
    pub network_token: Option<CardNetworkToken>,

    /// Customizes the payer experience during the 3DS Approval for payment.
    #[builder(default, setter(strip_option, into))]
    pub experience_context: Option<CardExperienceContext>,
}

#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, TypedBuilder)]
pub struct CardAttributes {
    /// The details about a customer in PayPal's system of record.
    #[builder(default, setter(strip_option, into))]
    pub customer: Option<CardCustomer>,

    /// Instruction to vault the card based on the specified strategy.
    #[builder(default, setter(strip_option, into))]
    pub vault: Option<CardVault>,

    /// Instruction to optionally verify the card based on the specified strategy.
    #[builder(default, setter(strip_option, into))]
    pub verification: Option<CardVerification>,
}

#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, TypedBuilder)]
pub struct CardCustomer {
    /// The unique ID for a customer generated by PayPal.
    #[builder(default, setter(strip_option, into))]
    pub id: Option<String>,

    /// Email address of the customer as provided to the merchant or on file with the merchant.
    /// Email Address is required if you are processing the transaction using PayPal Guest Processing which is offered to select partners and merchants.
    #[builder(default, setter(strip_option, into))]
    pub email_address: Option<String>,

    /// The phone number of the customer as provided to the merchant or on file with the merchant.
    /// The phone.phone_number supports only national_number.
    #[builder(default, setter(strip_option, into))]
    pub phone: Option<PhoneWithType>,

    /// The full name of the customer as provided to the merchant or on file with the merchant.
    #[builder(default, setter(strip_option, into))]
    pub name: Option<PersonFullName>,

    /// Merchants and partners may already have a data-store where their customer information is persisted.
    /// Use merchant_customer_id to associate the PayPal-generated customer.id to your representation of a customer.
    #[builder(default, setter(strip_option, into))]
    pub merchant_customer_id: Option<String>,
}

#[serde_with::skip_serializing_none]
