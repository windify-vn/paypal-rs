#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, TypedBuilder)]
pub struct CardPreviousTransactionReference {
    /// Transaction reference id returned by the scheme. For Visa and Amex, this is the "Tran id" field in response.
    /// For MasterCard, this is the "BankNet reference id" field in response.
    /// For Discover, this is the "NRID" field in response.
    /// The pattern we expect for this field from Visa/Amex/CB/Discover is numeric, Mastercard/BNPP is alphanumeric and Paysecure is alphanumeric with special character -.
    #[builder(default, setter(strip_option, into))]
    pub id: Option<String>,

    /// The date that the transaction was authorized by the scheme.
    /// This field may not be returned for all networks.
    /// MasterCard refers to this field as "BankNet reference date.
    #[builder(default, setter(strip_option, into))]
    pub date: Option<String>,

    /// Reference ID issued for the card transaction.
    /// This ID can be used to track the transaction across processors, card brands and issuing banks.
    #[builder(default, setter(strip_option, into))]
    pub acquirer_reference_number: Option<String>,

    /// Name of the card network through which the transaction was routed.
    #[builder(default, setter(strip_option, into))]
    pub network: Option<CardNetwork>,
}

#[derive(Debug, Serialize, Deserialize, Eq, PartialEq, Clone, Copy)]
#[allow(clippy::enum_variant_names)]
pub enum CardEciFlag {
    /// Mastercard non-3-D Secure transaction.
    #[serde(rename = "MASTERCARD_NON_3D_SECURE_TRANSACTION")]
    MastercardNon3dSecureTransaction,

    /// Mastercard attempted authentication transaction.
    #[serde(rename = "MASTERCARD_ATTEMPTED_AUTHENTICATION_TRANSACTION")]
    MastercardAttemptedAuthenticationTransaction,

    /// Mastercard fully authenticated transaction.
    #[serde(rename = "MASTERCARD_FULLY_AUTHENTICATED_TRANSACTION")]
    MastercardFullyAuthenticatedTransaction,

    /// VISA, AMEX, JCB, DINERS CLUB fully authenticated transaction.
    #[serde(rename = "FULLY_AUTHENTICATED_TRANSACTION")]
    FullyAuthenticatedTransaction,

    /// VISA, AMEX, JCB, DINERS CLUB attempted authentication transaction.
    #[serde(rename = "ATTEMPTED_AUTHENTICATION_TRANSACTION")]
    AttemptedAuthenticationTransaction,

    /// VISA, AMEX, JCB, DINERS CLUB non-3-D Secure transaction.
    #[serde(rename = "NON_3D_SECURE_TRANSACTION")]
    Non3dSecureTransaction,
}

#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, TypedBuilder)]
pub struct CardNetworkToken {
    /// Third party network token number.
    #[builder(default, setter(strip_option, into))]
    pub token: Option<String>,

    /// An Encrypted one-time use value that's sent along with Network Token.
    /// This field is not required to be present for recurring transactions.
    #[builder(default, setter(strip_option, into))]
    pub cryptogram: Option<String>,

    /// A TRID, or a Token Requestor ID, is an identifier used by merchants to request network tokens from card networks.
    /// A TRID is a precursor to obtaining a network token for a credit card primary account number (PAN), and will aid in enabling secure card on file (COF) payments and reducing fraud.
    #[builder(default, setter(strip_option, into))]
    pub token_requestor_id: Option<String>,

    /// The card expiration year and month, in Internet date format.
    #[builder(default, setter(into))]
    pub expiry: String,

    /// Electronic Commerce Indicator (ECI).
    /// The ECI value is part of the 2 data elements that indicate the transaction was processed electronically.
    /// This should be passed on the authorization transaction to the Gateway/Processor.
    #[builder(default, setter(strip_option, into))]
    pub eci_flag: Option<CardEciFlag>,
}

#[serde_with::skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, TypedBuilder)]
pub struct CardExperienceContext {
    /// The URL where the customer will be redirected upon successfully completing the 3DS challenge.
    #[builder(default, setter(strip_option, into))]
    pub return_url: Option<String>,

    /// The URL where the customer will be redirected upon cancelling the 3DS challenge.
    #[builder(default, setter(strip_option, into))]
    pub cancel_url: Option<String>,
}
